export const locale = () => (en() ? "en-US" : "tr-TR");

/** aynı türkçe kelime iki anlamda geçiyorsa "bağlam|metin" yazılır, türkçede bağlam atılır */
export function t(tr: string, vars?: Record<string, string | number>): string {
  let s = (en() && EN[tr]) || tr.replace(/^\p{Ll}+\|/u, "");
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
